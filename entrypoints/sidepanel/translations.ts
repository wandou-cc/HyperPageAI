export type MessageKey = keyof (typeof messages)["en"];

// Resolves one complete localized UI string from the selected interface locale.
export function t(locale: Locale, key: MessageKey): string {
  return messages[locale][key];
}

// Converts internal error codes and API status details into user-facing text.
export function formatError(locale: Locale, error: unknown): string {
  const raw = error instanceof Error ? error.message : String(error);
  if (raw.startsWith("modelCapabilityFailed:")) {
    const [, capability, ...details] = raw.split(":");
    const key = `capability_${capability}`;
    const label = key in messages.en ? t(locale, key as MessageKey) : capability;
    return `${t(locale, "modelCapabilityFailed")} (${label}): ${formatError(locale, details.join(":"))}`;
  }
  if (raw.startsWith("apiRequestFailed:")) {
    const [, status, ...bodyParts] = raw.split(":");
    const body = bodyParts.join(":");
    return `${t(locale, "apiRequestFailed")} (${status})${body ? `: ${body}` : ""}`;
  }
  if (raw.startsWith("pageAgentFailed:")) {
    return `${t(locale, "pageAgentFailed")}: ${raw.slice("pageAgentFailed:".length)}`;
  }
  if (raw in messages.en) return t(locale, raw as MessageKey);
  return raw || t(locale, "unknownError");
}
